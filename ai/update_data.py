def save_realtime(code,row):

    file=os.path.join(
        REALTIME_DIR,
        str(code).zfill(6)+".csv"
    )


    df=pd.DataFrame(
        [row]
    )


    if os.path.exists(file):

        old=pd.read_csv(
            file
        )

        df=pd.concat(
            [
                old,
                df
            ],
            ignore_index=True
        )


    df.to_csv(
        file,
        index=False,
        encoding="utf-8-sig"
    )



