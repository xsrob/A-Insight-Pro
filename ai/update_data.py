def make_features(df):

    df=df.copy()


    df["return"]=(
        df["close"]
        .pct_change()
    )


    df["ma5"]=(
        df["close"]
        .rolling(5)
        .mean()
    )


    df["ma10"]=(
        df["close"]
        .rolling(10)
        .mean()
    )


    df["ma20"]=(
        df["close"]
        .rolling(20)
        .mean()
    )


    df["ma60"]=(
        df["close"]
        .rolling(60)
        .mean()
    )


    df["volume_change"]=(
        df["volume"]
        .pct_change()
    )


    df["volatility"]=(
        df["return"]
        .rolling(20)
        .std()
    )


    delta=df["close"].diff()


    gain=(
        delta.clip(lower=0)
        .rolling(14)
        .mean()
    )


    loss=(
        -delta.clip(upper=0)
        .rolling(14)
        .mean()
    )


    rs=gain/loss.replace(
        0,
        1e-9
    )


    df["rsi"]=100-(100/(1+rs))


    ema12=(
        df["close"]
        .ewm(
            span=12,
            adjust=False
        )
        .mean()
    )


    ema26=(
        df["close"]
        .ewm(
            span=26,
            adjust=False
        )
        .mean()
    )


    df["macd"]=ema12-ema26


    return df.dropna()



