def market_code(code):

    code=str(code).zfill(6)

    if code.startswith(("5","6")):

        return "sh"+code

    return "sz"+code



# =========================
# 获取实时价格
# =========================

def get_price(code):

    url=(
        "https://qt.gtimg.cn/q="
        +
        market_code(code)
    )

    try:

        r=requests.get(
            url,
            timeout=10,
            headers={
                "User-Agent":
                "Mozilla/5.0"
            }
        )


        if r.text.startswith("v_"):

            data=r.text.split("~")

            return {

                "date":
                pd.Timestamp.now()
                .strftime("%Y-%m-%d %H:%M:%S"),

                "price":
                float(data[3])

            }


    except Exception:

        pass


    return None



