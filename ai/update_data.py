# =========================
# 清理异常
# =========================

def clean_history(df):

    if len(df)==0:

        return df


    df=df.copy()


    df["date"]=(
        df["date"]
        .astype(str)
    )


    # 删除14位分钟时间

    df=df[
        ~df["date"]
        .str.match(
            r"^\d{14}$"
        )
    ]



    # 删除成交量0

    if "volume" in df.columns:

        df=df[
            df["volume"]>0
        ]



    return df



