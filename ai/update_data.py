def update():

    init()


    print("================")
    print("A-Insight 行情系统 V3.0")
    print("================")


    stocks=pd.read_csv(
        STOCK_LIST,
        dtype={
            "code":str
        }
    )


    stocks["code"]=(
        stocks["code"]
        .str.zfill(6)
    )


    total=len(stocks)


    for i,row in stocks.iterrows():


        code=row["code"]


        print(
            f"[{i+1}/{total}] {code}"
        )


        try:

            market=get_price(code)


            if market is None:

                continue



            # 保存实时

            save_realtime(
                code,
                market
            )


            # 历史保护

            df=load_history(code)


            df=clean_history(df)



            save_history(
                code,
                df
            )


        except Exception:


            log_error(
                traceback.format_exc()
            )


        time.sleep(
            random.uniform(
                0.3,
                0.8
            )
        )


    print("================")
    print("实时行情更新完成")
    print("================")

    # Also sync historical OHLCV data
    sync_history(stocks)


